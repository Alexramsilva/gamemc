def valor_cartera():

    total = 0

    for ticker in ACTIVOS:

        cantidad = st.session_state.cartera[ticker]

        precio = st.session_state.precios.get(
            ticker,
            0
        )

        total += cantidad * precio

    return total


def patrimonio():

    return (
        st.session_state.efectivo
        + valor_cartera()
    )


def rendimiento():

    return (
        patrimonio() / 10000 - 1
    ) * 100


