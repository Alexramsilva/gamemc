def vender(ticker, cantidad):

    if (
        cantidad
        <= st.session_state.cartera[ticker]
    ):

        precio = st.session_state.precios[ticker]

        ingreso = precio * cantidad

        st.session_state.cartera[ticker] -= cantidad

        st.session_state.efectivo += ingreso

